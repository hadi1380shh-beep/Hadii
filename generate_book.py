def set_rtl(paragraph):
    """Set paragraph to RTL and right aligned"""
    p = paragraph._p
    pPr = p.get_or_add_pPr()
    # bidi
    bidi = OxmlElement('w:bidi')
    bidi.set(qn('w:val'), '1')
    pPr.append(bidi)
    # jc right
    jc = pPr.find(qn('w:jc'))
    if jc is None:
        jc = OxmlElement('w:jc')
        pPr.append(jc)
    jc.set(qn('w:val'), 'right')
    paragraph.alignment = WD_ALIGN_PARAGRAPH.RIGHT

def add_bidi_to_paragraph(paragraph):
    pPr = paragraph._p.get_or_add_pPr()
    # Check if bidi exists
    if pPr.find(qn('w:bidi')) is None:
        bidi = OxmlElement('w:bidi')
        bidi.set(qn('w:val'), '1')
        pPr.append(bidi)

def set_font(run, name="B Nazanin", size=13, bold=False, color=None, italic=False):
    run.font.name = name
    run.font.size = Pt(size)
    run.bold = bold
    run.italic = italic
    if color:
        run.font.color.rgb = RGBColor.from_string(color)
    # For Persian, set complex script font
    r = run._element
    rPr = r.get_or_add_rPr()
    rFonts = rPr.find(qn('w:rFonts'))
    if rFonts is None:
        rFonts = OxmlElement('w:rFonts')
        rPr.append(rFonts)
    rFonts.set(qn('w:ascii'), name)
    rFonts.set(qn('w:hAnsi'), name)
    rFonts.set(qn('w:cs'), name)
    rFonts.set(qn('w:eastAsia'), name)

def add_horizontal_line(paragraph, color="8B0000", width_pt=1):
    p = paragraph._p
    pPr = p.get_or_add_pPr()
    pBdr = OxmlElement('w:pBdr')
    bottom = OxmlElement('w:bottom')
    bottom.set(qn('w:val'), 'single')
    bottom.set(qn('w:sz'), str(width_pt*4))
    bottom.set(qn('w:space'), '6')
    bottom.set(qn('w:color'), color)
    pBdr.append(bottom)
    pPr.append(pBdr)

def set_margins(section, top=1.8, bottom=1.8, left=1.8, right=1.8):
    section.top_margin = Cm(top)
    section.bottom_margin = Cm(bottom)
    section.left_margin = Cm(left)
    section.right_margin = Cm(right)
    section.header_distance = Cm(1)
    section.footer_distance = Cm(1)

def set_paragraph_spacing(paragraph, before=0, after=6, line_spacing=1.4):
    pf = paragraph.paragraph_format
    pf.space_before = Pt(before)
    pf.space_after = Pt(after)
    pf.line_spacing = line_spacing
    pf.alignment = WD_ALIGN_PARAGRAPH.RIGHT
    # widow control
    pPr = paragraph._p.get_or_add_pPr()
    widow = OxmlElement('w:widowControl')
    widow.set(qn('w:val'), '1')
    pPr.append(widow)

