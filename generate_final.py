# ==================== Helpers ====================
def set_rtl(paragraph):
    p = paragraph._p
    pPr = p.get_or_add_pPr()
    # bidi
    if pPr.find(qn('w:bidi')) is None:
        bidi = OxmlElement('w:bidi')
        bidi.set(qn('w:val'), '1')
        pPr.append(bidi)
    # jc right
    jc = pPr.find(qn('w:jc'))
    if jc is None:
        jc = OxmlElement('w:jc')
        pPr.append(jc)
    jc.set(qn('w:val'), 'right')
    paragraph.alignment = WD_ALIGN_PARAGRAPH.RIGHT

def set_font(run, name="B Nazanin", size=12.5, bold=False, color=None, italic=False):
    run.font.name = name
    run.font.size = Pt(size)
    run.bold = bold
    run.italic = italic
    if color:
        run.font.color.rgb = RGBColor.from_string(color)
    r = run._element
    rPr = r.get_or_add_rPr()
    rFonts = rPr.find(qn('w:rFonts'))
    if rFonts is None:
        rFonts = OxmlElement('w:rFonts')
        rPr.append(rFonts)
    # Set all font slots to same Persian font for consistency
    rFonts.set(qn('w:ascii'), name)
    rFonts.set(qn('w:hAnsi'), name)
    rFonts.set(qn('w:cs'), name)
    rFonts.set(qn('w:eastAsia'), name)
    # Set bidi flag for run
    # keep rtl

def set_para(paragraph, before=0, after=6, line_spacing=1.55):
    pf = paragraph.paragraph_format
    pf.space_before = Pt(before)
    pf.space_after = Pt(after)
    pf.line_spacing = line_spacing
    pf.alignment = WD_ALIGN_PARAGRAPH.RIGHT
    pf.widow_control = True
    # add bidi to pPr
    pPr = paragraph._p.get_or_add_pPr()
    if pPr.find(qn('w:bidi')) is None:
        b = OxmlElement('w:bidi')
        b.set(qn('w:val'), '1')
        pPr.append(b)

def add_h1(doc, text, size=16, color="8B1A1A", before=18, after=10):
    p = doc.add_paragraph()
    set_rtl(p)
    run = p.add_run(text)
    set_font(run, "B Nazanin", size, bold=True, color=color)
    set_para(p, before=before, after=after)
    # bottom border + shading
    pPr = p._p.get_or_add_pPr()
    pBdr = OxmlElement('w:pBdr')
    bottom = OxmlElement('w:bottom')
    bottom.set(qn('w:val'), 'single')
    bottom.set(qn('w:sz'), '6')
    bottom.set(qn('w:space'), '6')
    bottom.set(qn('w:color'), color)
    pBdr.append(bottom)
    pPr.append(pBdr)
    shd = OxmlElement('w:shd')
    shd.set(qn('w:val'), 'clear')
    shd.set(qn('w:color'), 'auto')
    shd.set(qn('w:fill'), 'FFF5F5')
    pPr.append(shd)
    return p

