    # Arabic text
    run = p.add_run(arabic)
    set_font(run, "Traditional Arabic", 13.5, color="0D3311")
    # make it bold? Quran usually not bold but we make slightly larger
    set_para(p, before=6, after=2)
    p.alignment = WD_ALIGN_PARAGRAPH.CENTER
    # need to re-set rtl? center is okay but bidi still
    # Translation
    p2 = doc.add_paragraph()
    set_rtl(p2)
    pf = p2.paragraph_format
    pf.right_indent = Cm(0.8)
    pf.left_indent = Cm(0.5)
    run2 = p2.add_run("ترجمه: " + translation)
    set_font(run2, "B Nazanin", 10.5, italic=True, color="333333")
    set_para(p2, before=1, after=8, line_spacing=1.35)
