def add_ayat(doc, arabic, translation, source=""):
    # Arabic ayah box
    p = doc.add_paragraph()
    set_rtl(p)
    pPr = p._p.get_or_add_pPr()
    # Right thick border
    pBdr = OxmlElement('w:pBdr')
    right = OxmlElement('w:right')
    right.set(qn('w:val'), 'single')
    right.set(qn('w:sz'), '18')
    right.set(qn('w:space'), '8')
    right.set(qn('w:color'), '1B5E20')
    pBdr.append(right)
    pPr.append(pBdr)
    # shading light green
    shd = OxmlElement('w:shd')
    shd.set(qn('w:val'), 'clear')
    shd.set(qn('w:color'), 'auto')
    shd.set(qn('w:fill'), 'E8F5E9')
